export function isReceiptImageLookupRequest(message: string) {
  return /(บิล|ใบเสร็จ|สลิป|ocr|receipt|payment slip)/i.test(message) &&
    /(สรุป|ยอด|รวม|ocr|ล่าสุด|ดึง|อ่าน|สแกน|ทำรายการ|บันทึก)/i.test(message);
}

export function selfContainedAssistantFallback(message: string) {
  const text = message.normalize('NFC').trim();
  const ignoresAppData = /(ไม่ต้อง|ไม่จำเป็นต้อง|ห้าม)\s*(?:ดู|ใช้|อ่าน|ดึง).*ข้อมูล.*(?:แอป|ระบบ)|แบบทั่วไป/i.test(text);

  if (ignoresAppData && /(อ่านหนังสือ|ทบทวน|เตรียมสอบ|ก่อนสอบ|การเรียน)/i.test(text)) {
    return [
      'ได้ครับ แนะนำแบบทั่วไปโดยไม่ใช้ข้อมูลในแอป',
      '1. Active Recall: อ่านช่วงสั้น ๆ แล้วปิดหนังสือตอบหรือเขียนสิ่งที่จำได้',
      '2. Spaced Repetition: กลับมาทวนเรื่องเดิมแบบเว้นระยะ เช่น วันนี้ พรุ่งนี้ และอีก 3 วัน',
      '3. Practice Test: ทำโจทย์หรือข้อสอบเก่าแบบจับเวลา แล้วทวนเฉพาะข้อที่ผิด',
      '4. อ่านรอบละ 40-50 นาที พัก 10 นาที และวางโทรศัพท์ให้พ้นมือ',
      'เริ่มจากหัวข้อที่ออกสอบมากหรือยังอ่อนที่สุดก่อน แล้วค่อยเก็บหัวข้อที่มั่นใจครับ',
    ].join('\n');
  }

  const days = examCountdownDays(text);
  if (days && /(ตารางอ่าน|วางแผน.*อ่าน|ยัง.*(?:ไม่เริ่ม|ไม่ได้อ่าน)|เตรียมสอบ)/i.test(text)) {
    return examCountdownPlan(days);
  }

  if (/(ช่วย)?(?:จัดชีวิต|จัดระเบียบชีวิต|วางแผนชีวิต)(?:ช่วงนี้)?/i.test(text)) {
    return [
      'ได้ครับ เริ่มจัดชีวิตช่วงนี้แบบไม่ให้หนักเกินไปก่อน',
      '1. เขียนทุกเรื่องที่ค้างอยู่ลงรายการเดียว ใช้เวลาไม่เกิน 10 นาที',
      '2. เลือก 3 เรื่องสำคัญของสัปดาห์: งานหรือเรียน 1 เรื่อง การเงิน 1 เรื่อง และสุขภาพ 1 เรื่อง',
      '3. พรุ่งนี้กำหนดงานสำคัญที่สุดเพียง 1 ชิ้นเป็นช่วงโฟกัส 45 นาที แล้วตามด้วยงานเล็ก 2 ชิ้น',
      '4. กันเวลาพัก อาหาร และนอนให้ชัด เพราะแผนที่แน่นเกินไปมักทำต่อไม่ได้',
      'ถ้าบอกสิ่งที่กังวลที่สุด 2-3 เรื่องกับเวลาว่างพรุ่งนี้ ฉันจะช่วยเรียงเป็นแผนรายเวลาให้ครับ',
    ].join('\n');
  }

  if (/ปิดอินเทอร์เน็ต|ออฟไลน์|offline/i.test(text) && /(ข้อมูล|ตาราง|งาน|งบ|สลิป)/i.test(text)) {
    return 'ตอนนี้ออฟไลน์จึงดึงข้อมูลล่าสุดจากบัญชีไม่ได้ครับ ฉันจะไม่เดาข้อมูลงานหรือยอดเงินให้ เมื่อเชื่อมต่ออินเทอร์เน็ตแล้วส่งคำถามเดิมอีกครั้งได้เลย';
  }

  return '';
}
