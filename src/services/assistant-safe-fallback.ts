function examCountdownDays(message: string) {
  const match = /(?:สอบ(?:อีก)?|อีก)\s*(\d+)\s*วัน/i.exec(message);
  if (!match) return null;
  const days = Number(match[1]);
  return Number.isFinite(days) && days > 0 ? Math.min(days, 30) : null;
}

